import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, linkSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { test } from "node:test";

// install.ps1 写的启动脚本 bin\speakmore.cmd。它照 current 找 versions 下的程序；从旧版本升上来、启动脚本变了时，
// 旧的那份可能正跑着（speakmore update 就是它起的）就被改写，cmd 等程序退出后从原来的字节位置接着读。
// 后两条要在 Windows 上真的起 cmd，"程序"是改名成 electron.exe 的 node。

const INSTALLER = resolve(import.meta.dirname, "..", "..", "install.ps1");
const windowsOnly = { skip: process.platform !== "win32" && "要在 Windows 上起 cmd" };

/** 0.9.0–0.9.2 的 install.ps1 写的启动脚本，原样 */
const LEGACY_LAUNCHER = `${[
  "@echo off",
  "rem The speakmore command, generated by the SpeakMore installer.",
  "rem Runs on the bundled Electron as Node, so Node does not need to be installed.",
  "setlocal",
  'if not defined SPEAKMORE_HOME for %%I in ("%~dp0..") do set "SPEAKMORE_HOME=%%~fI"',
  "set ELECTRON_RUN_AS_NODE=1",
  '"%~dp0..\\runtime\\electron.exe" "%~dp0..\\app\\bin\\speakmore.mjs" %*',
].join("\r\n")}\r\n`;

/** 0.9.3 起的 install.ps1 写的启动脚本，原样。发出去了就不再改：以后的版本从它这里升级时，它也可能正跑着 */
const LAUNCHER_0_9_3 = `${[
  "@echo off",
  "setlocal",
  'if not defined SPEAKMORE_HOME for %%I in ("%~dp0..") do set "SPEAKMORE_HOME=%%~fI"',
  'set /p SPEAKMORE_CURRENT=<"%~dp0..\\current"',
  "set ELECTRON_RUN_AS_NODE=1",
  '"%~dp0..\\versions\\%SPEAKMORE_CURRENT%\\runtime\\electron.exe" "%~dp0..\\versions\\%SPEAKMORE_CURRENT%\\app\\bin\\speakmore.mjs" %*',
].join("\r\n")}\r\n`;

/** 发出去过的每一版启动脚本。改了 install.ps1 里的启动脚本、发了版，就把新的那版加进来 */
const SHIPPED_LAUNCHERS = { "0.9.0–0.9.2": LEGACY_LAUNCHER, "0.9.3": LAUNCHER_0_9_3 };

/** 照 install.ps1 里 $LauncherText 那几行拼出它写进文件的内容：单引号字符串，'' 是一个 ' */
function launcher() {
  const source = readFileSync(INSTALLER, "utf8");
  const block = /\$LauncherText = @\(\r?\n([\s\S]*?)\r?\n\s*\) -join "`r`n"/.exec(source);
  assert.ok(block, "install.ps1 里找不到 $LauncherText");
  const lines = [...block[1].matchAll(/^\s*'((?:[^']|'')*)',?\s*$/gm)].map((match) => match[1].replaceAll("''", "'"));
  return `${lines.join("\r\n")}\r\n`;
}

/** 在 dir 里放一个"electron.exe"：其实是 node（硬链接，不同盘时复制） */
function fakeElectron(dir) {
  mkdirSync(dir, { recursive: true });
  const exe = join(dir, "electron.exe");
  try {
    linkSync(process.execPath, exe);
  } catch {
    copyFileSync(process.execPath, exe);
  }
}

function runCmd(file, args = []) {
  return spawnSync("cmd", ["/d", "/c", file, ...args], { encoding: "utf8", windowsHide: true });
}

test("启动脚本不比发出去过的任何一版长：旧的正跑着时被改写，cmd 接着读到的是文件末尾", () => {
  const text = launcher();
  for (const [version, shipped] of Object.entries(SHIPPED_LAUNCHERS)) {
    assert.ok(
      Buffer.byteLength(text) <= Buffer.byteLength(shipped),
      `新的 ${Buffer.byteLength(text)} 字节，${version} 的 ${Buffer.byteLength(shipped)} 字节`,
    );
  }
  assert.match(text, /set \/p SPEAKMORE_CURRENT=<"%~dp0\.\.\\current"/);
  assert.match(text, /"%~dp0\.\.\\versions\\%SPEAKMORE_CURRENT%\\runtime\\electron\.exe"/);
  assert.ok(text.endsWith("%*\r\n"), "调程序的那一行要是最后一行");
});

test("启动脚本照 current 起 versions 下的那个版本，参数原样带过去，家目录是它所在的那个", windowsOnly, (t) => {
  const home = mkdtempSync(join(tmpdir(), "sm-launcher-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const version = join(home, "versions", "0.1.0-1a2b3c4d");
  fakeElectron(join(version, "runtime"));
  mkdirSync(join(version, "app", "bin"), { recursive: true });
  writeFileSync(
    join(version, "app", "bin", "speakmore.mjs"),
    "console.log(JSON.stringify({ home: process.env.SPEAKMORE_HOME, args: process.argv.slice(2), node: process.env.ELECTRON_RUN_AS_NODE }));\n",
  );
  writeFileSync(join(home, "current"), "0.1.0-1a2b3c4d");
  mkdirSync(join(home, "bin"));
  writeFileSync(join(home, "bin", "speakmore.cmd"), launcher());

  const result = runCmd(join(home, "bin", "speakmore.cmd"), ["status", "--json"]);
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(JSON.parse(result.stdout), { home, args: ["status", "--json"], node: "1" });
});

test(
  "0.9.2 的启动脚本正跑着时被改写成新的：程序退出后 cmd 读到文件末尾，正常结束；新的要是更长就会出错",
  windowsOnly,
  (t) => {
    const home = mkdtempSync(join(tmpdir(), "sm-launcher-"));
    t.after(() => rmSync(home, { recursive: true, force: true }));
    fakeElectron(join(home, "runtime"));
    mkdirSync(join(home, "app", "bin"), { recursive: true });
    mkdirSync(join(home, "bin"));
    const cmdFile = join(home, "bin", "speakmore.cmd");
    // 程序（像 speakmore update 跑的安装脚本那样）把正在跑它的启动脚本改写掉，再退出
    writeFileSync(
      join(home, "app", "bin", "speakmore.mjs"),
      `import { writeFileSync } from "node:fs";\nwriteFileSync(${JSON.stringify(cmdFile)}, process.env.NEXT_LAUNCHER);\nconsole.log("updated");\n`,
    );

    const rewrite = (next) => {
      writeFileSync(cmdFile, LEGACY_LAUNCHER);
      return spawnSync("cmd", ["/d", "/c", cmdFile], {
        encoding: "utf8",
        windowsHide: true,
        env: { ...process.env, NEXT_LAUNCHER: next },
      });
    };

    const ok = rewrite(launcher());
    assert.equal(ok.status, 0, ok.stderr);
    assert.equal(ok.stdout.trim(), "updated");
    assert.equal(ok.stderr, "");

    // 对照：新内容比旧的长时，cmd 从旧的长度处接着读，读到的是半截命令
    const longer = rewrite(`${launcher()}rem ${"x".repeat(80)}\r\necho should-not-run-from-the-middle\r\n`);
    assert.notEqual(`${longer.stdout}${longer.stderr}`.replace("updated", "").trim(), "");
  },
);
